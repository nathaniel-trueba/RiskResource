"""
Build the frontend data file from FEMA's National Risk Index (county table).

Usage:
    python scripts/build_data.py path/to/NRI_Table_Counties.csv path/to/NRI_HazardInfo.csv

Writes: data/risk-data.js   (sets window.RISK_DATA)

Later, the backend (FastAPI / Lambda) can return this same JSON shape from an
endpoint, and js/config.js can be pointed at it instead of the static file.
"""
import json
import sys
from pathlib import Path

import pandas as pd

COUNTY_CSV = Path(sys.argv[1] if len(sys.argv) > 1 else "NRI_Table_Counties.csv")
HAZARD_CSV = Path(sys.argv[2] if len(sys.argv) > 2 else "NRI_HazardInfo.csv")
OUT = Path(__file__).resolve().parent.parent / "data" / "risk-data.js"

HIGH_RATINGS = {"Very High", "Relatively High"}

nri = pd.read_csv(COUNTY_CSV, low_memory=False)
haz = pd.read_csv(HAZARD_CSV, encoding="utf-8-sig")
hazard_names = dict(zip(haz["Prefix"], haz["Hazard"]))
hazard_cols = {p: f"{p}_EALT" for p in hazard_names if f"{p}_EALT" in nri.columns}
version = str(haz["NRI_VER"].iloc[0]) if "NRI_VER" in haz else "unknown"


def num(v, digits=2):
    """JSON-safe number (NaN -> None)."""
    return None if pd.isna(v) else round(float(v), digits)


def top_hazards(row_or_series, n=3):
    vals = {p: row_or_series[c] for p, c in hazard_cols.items()}
    vals = {p: v for p, v in vals.items() if pd.notna(v) and v > 0}
    best = sorted(vals.items(), key=lambda kv: kv[1], reverse=True)[:n]
    return [{"hazard": hazard_names[p], "eal": round(float(v))} for p, v in best]


# ---------------- Counties ----------------
counties = {}
for _, r in nri.iterrows():
    fips = f"{int(r['STCOFIPS']):05d}"
    pop = r["POPULATION"]
    counties[fips] = {
        "name": f"{r['COUNTY']} {r['COUNTYTYPE']}".strip(),
        "state": r["STATE"],
        "population": int(pop) if pd.notna(pop) else None,
        "risk_score": num(r["RISK_SCORE"]),
        "risk_rating": r["RISK_RATNG"] if pd.notna(r["RISK_RATNG"]) else "No Rating",
        "eal_total": num(r["EAL_VALT"], 0),
        "eal_per_person": num(r["EAL_VALT"] / pop) if pop else None,
        "sovi_score": num(r["SOVI_SCORE"]),
        "resl_score": num(r["RESL_SCORE"]),
        "top_hazards": top_hazards(r),
    }

# ---------------- States (rolled up from counties) ----------------
states = {}
for (sfips, sname), g in nri.groupby(["STATEFIPS", "STATE"]):
    pop = g["POPULATION"].sum()
    eal = g["EAL_VALT"].sum()
    high_pop = g.loc[g["RISK_RATNG"].isin(HIGH_RATINGS), "POPULATION"].sum()
    states[f"{int(sfips):02d}"] = {
        "name": sname,
        "population": int(pop),
        "counties": int(len(g)),
        "eal_total": round(float(eal)),
        "eal_per_person": num(eal / pop) if pop else None,
        "pct_pop_high_risk": num(100 * high_pop / pop, 1) if pop else None,
        "high_risk_counties": int(g["RISK_RATNG"].isin(HIGH_RATINGS).sum()),
        "top_hazards": top_hazards(g[list(hazard_cols.values())].sum()),
    }

payload = {
    "source": "FEMA National Risk Index",
    "version": version,
    "states": states,
    "counties": counties,
}

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// Generated by scripts/build_data.py - do not edit by hand.\n"
    "window.RISK_DATA = " + json.dumps(payload, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {OUT} ({OUT.stat().st_size / 1e6:.2f} MB): "
      f"{len(states)} states/territories, {len(counties)} counties")
